"""Station SAM 3.1 segmentation, behind an ONNX Runtime seam.

The station's segmentation runtime is ONNX Runtime on both targets:

- on the station GPU, the same session code requests the CUDA
  execution provider (an `onnxruntime-gpu` install provides it);
- in tests and CI, the CPU provider executes a tiny fake SAM3 ONNX
  model (`tests/fixtures/sam3_fake/`, generated by
  `scripts/make_fake_sam3_model.py`).

There is no separate test path: `Sam3Detector`'s preprocessing,
session calls, and mask post-processing are identical for the fake
model on CPU and the real SAM 3.1 export on GPU. Only the model file
and the execution provider differ.

Model contract (what a SAM 3.1 ONNX export must provide, and what
the fake implements): input `image` float32 [1, 3, H, W] in 0..1;
outputs `masks` float32 [1, N, H, W] probabilities and `scores`
float32 [1, N]. The real checkpoint is license-gated and large, so
exporting it is a station provisioning step, not something CI
fetches: export SAM 3.1 to ONNX with that contract on the station
and point `--sam3-model` at it.
"""

from __future__ import annotations

import asyncio
import importlib
from dataclasses import replace
from pathlib import Path
from typing import Any, Protocol, cast

import numpy as np
from numpy.typing import NDArray

from surmap.detection.detector import decode_rgb
from surmap.survey.sam import RawFrame, SamDetection
from surmap.survey.stereo import FrameImage


class Sam3Unavailable(RuntimeError):
    """Raised when the SAM 3.1 runtime or model cannot be used."""


def parse_sam_device(device: str) -> tuple[str, int | None]:
    """A SAM device string as (kind, CUDA index): `cuda:2`, `cuda`, `2`,
    `gpu:1`, `cpu` or `auto`. Anything else is a `ValueError`."""
    spec = device.strip().lower()
    if spec in ("cpu", "auto"):
        return spec, None
    if spec.isdigit():
        return "cuda", int(spec)
    for prefix in ("cuda", "gpu"):
        if spec == prefix:
            return "cuda", 0
        if spec.startswith(f"{prefix}:") and spec[len(prefix) + 1 :].isdigit():
            return "cuda", int(spec[len(prefix) + 1 :])
    raise ValueError(f"unknown SAM device: {device!r} (use cpu, auto, cuda or cuda:<index>)")


class Sam3Session(Protocol):
    """One loaded model: image tensor in, (masks, scores) out."""

    @property
    def provider(self) -> str: ...

    @property
    def device(self) -> str: ...

    @property
    def input_size(self) -> tuple[int, int]: ...

    def run(
        self, image_chw: NDArray[np.float32]
    ) -> tuple[NDArray[np.float32], NDArray[np.float32]]: ...


class OnnxSam3Session:
    """`Sam3Session` over ONNX Runtime (CUDA preferred when asked)."""

    def __init__(self, model_path: Path, *, device: str = "auto") -> None:
        if not model_path.is_file():
            raise Sam3Unavailable(
                f"SAM 3.1 model not found at {model_path}; provision it on the station "
                "(see the sam3 module docs) or use the fake test model"
            )
        try:
            ort = importlib.import_module("onnxruntime")
        except ImportError as exc:
            raise Sam3Unavailable("onnxruntime is not importable") from exc
        available = cast(list[str], ort.get_available_providers())
        kind, device_id = parse_sam_device(device)
        self._device = f"cuda:{device_id}" if kind == "cuda" else kind
        providers: list[Any]
        if kind == "cuda":
            if "CUDAExecutionProvider" not in available:
                raise Sam3Unavailable(
                    "CUDA execution provider is not available; install onnxruntime-gpu "
                    "on the station (the same session code runs, only the provider differs)"
                )
            providers = [
                ("CUDAExecutionProvider", {"device_id": device_id or 0}),
                "CPUExecutionProvider",
            ]
        elif kind == "cpu":
            providers = ["CPUExecutionProvider"]
        else:  # auto
            providers = [
                p for p in ("CUDAExecutionProvider", "CPUExecutionProvider") if p in available
            ]
        self._session: Any = ort.InferenceSession(str(model_path), providers=providers)
        self._provider = str(self._session.get_providers()[0])
        input_shape = self._session.get_inputs()[0].shape
        height = input_shape[2] if isinstance(input_shape[2], int) else 256
        width = input_shape[3] if isinstance(input_shape[3], int) else 256
        self._input_size = (int(width), int(height))

    @property
    def provider(self) -> str:
        return self._provider

    @property
    def device(self) -> str:
        """The requested device, normalised (`cuda:<index>`, `cpu`, `auto`)."""
        return self._device

    @property
    def input_size(self) -> tuple[int, int]:
        return self._input_size

    def run(
        self, image_chw: NDArray[np.float32]
    ) -> tuple[NDArray[np.float32], NDArray[np.float32]]:
        input_name = self._session.get_inputs()[0].name
        outputs = cast(list[NDArray[np.float32]], self._session.run(None, {input_name: image_chw}))
        by_name = {
            output.name: result
            for output, result in zip(self._session.get_outputs(), outputs, strict=True)
        }
        return by_name["masks"], by_name["scores"]


def mask_outline(
    mask: NDArray[np.bool_], scale_x: float, scale_y: float, max_points: int = 96
) -> tuple[tuple[float, float], ...]:
    """A coarse outline of one binary mask.

    Each point is ``(column * scale_x, row * scale_y)``. There is no
    extra origin: a mask that covers a box, rather than the whole
    frame, is shifted by the caller.
    """
    rows = np.nonzero(mask.any(axis=1))[0]
    if len(rows) == 0:
        return ()
    step = max(1, len(rows) // (max_points // 2))
    left: list[tuple[float, float]] = []
    right: list[tuple[float, float]] = []
    for row in rows[::step]:
        columns = np.nonzero(mask[row])[0]
        left.append((float(columns[0]) * scale_x, float(row) * scale_y))
        right.append((float(columns[-1]) * scale_x, float(row) * scale_y))
    return tuple(left + right[::-1])


