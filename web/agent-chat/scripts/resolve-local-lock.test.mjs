// @vitest-environment node
import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createServer } from "node:http";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterAll, afterEach, beforeAll, beforeEach, describe, expect, it } from "vitest";

const SCRIPT = fileURLToPath(new URL("./resolve-local-lock.mjs", import.meta.url));
const PUBLIC = "https://registry.yarnpkg.com";

// name -> version -> dist: the versions the fake registry serves.

let served = {};
let registryUrl = "";
let server;
let root = "";

function sha1(text) {
  return createHash("sha1").update(text).digest("hex");
}

function integrityOf(name, version) {
  return `sha512-${createHash("sha512").update(`${name}@${version}`).digest("base64")}`;
}

function dist(name, version) {
  return { shasum: sha1(`${name}@${version}`), integrity: integrityOf(name, version) };
}

function publish(name, ...versions) {
  served[name] = Object.fromEntries(versions.map((v) => [v, dist(name, v)]));
}

function versionDocument(name, version) {
  const base = `${registryUrl}/${name}/-/${name.split("/").at(-1)}-${version}.tgz`;
  return { name, version, dist: { tarball: base, ...served[name][version] } };
}

function packageDocument(name) {
  const versions = Object.fromEntries(
    Object.keys(served[name]).map((v) => [v, versionDocument(name, v)]),
  );
  const latest = Object.keys(served[name]).sort().at(-1);
  return { name, versions, "dist-tags": { latest } };
}

beforeAll(async () => {
  server = createServer((req, res) => {
    const path = decodeURIComponent((req.url ?? "/").split("?")[0]).slice(1);
    const exact = path.match(/^(.+)\/(\d+\.\d+\.\d+[^/]*)$/);
    const send = (status, body) => {
      res.writeHead(status, { "content-type": "application/json" });
      res.end(JSON.stringify(body));
    };
    if (exact && served[exact[1]]?.[exact[2]]) return send(200, versionDocument(exact[1], exact[2]));
    if (served[path]) return send(200, packageDocument(path));
    send(404, { error: "not found" });
  });
  await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
  const address = server.address();
  if (typeof address !== "object" || address === null) throw new Error("no port");
  registryUrl = `http://127.0.0.1:${address.port}`;
});

afterAll(() => {
  server.close();
});

afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

beforeEach(() => {
  served = {};
  root = mkdtempSync(join(tmpdir(), "resolve-local-lock-"));
  // Empty caches, so the lookup never reads this machine's real package caches.
  for (const dir of ["yarn-cache", "npm-cache", "bun-cache"]) mkdirSync(join(root, dir));
});

function lockBlock(keys, name, version, host = "https://npm.dev.wixpress.com/api/npm/npm-repos") {
  const file = name.split("/").at(-1);
  const d = dist(name, version);
  const header = keys.map((k) => `"${k}"`).join(", ");
  return [
    `${header}:`,
    `  version "${version}"`,
    `  resolved "${host}/${name}/-/${file}-${version}.tgz#${d.shasum}"`,
    `  integrity ${d.integrity}`,
    "",
  ].join("\n");
}

function writeProject(packageJson, blocks) {
  writeFileSync(join(root, "package.json"), `${JSON.stringify(packageJson, null, 2)}\n`);
  writeFileSync(
    join(root, "yarn.lock"),
    ["# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.", "# yarn lockfile v1", "", ...blocks].join("\n"),
  );
}

function readLock() {
  return readFileSync(join(root, "yarn.lock"), "utf-8");
}

function readPackageJson() {
  return JSON.parse(readFileSync(join(root, "package.json"), "utf-8"));
}

function run(args, registry = registryUrl) {
  const env = {
    ...process.env,
    LOCAL_REGISTRY_URL: registry,
    YARN_CACHE_FOLDER: join(root, "yarn-cache"),
    npm_config_cache: join(root, "npm-cache"),
    BUN_INSTALL_CACHE_DIR: join(root, "bun-cache"),
  };
  return new Promise((resolve) => {
    execFile(process.execPath, [SCRIPT, "--project", root, ...args], { env }, (error, stdout, stderr) => {
      resolve({ code: error ? (typeof error.code === "number" ? error.code : 1) : 0, output: `${stdout}${stderr}` });
    });
  });
}

describe("resolve-local-lock", () => {
  it("keeps an exact version the private registry serves and points resolved at the public registry", async () => {
    publish("left-pad", "1.3.0");
    writeProject({ dependencies: { "left-pad": "^1.3.0" } }, [lockBlock(["left-pad@^1.3.0"], "left-pad", "1.3.0")]);

    const result = await run([]);

    expect(result.code).toBe(0);
    expect(readLock()).toContain(`  version "1.3.0"`);
    expect(readLock()).toContain(
      `  resolved "${PUBLIC}/left-pad/-/left-pad-1.3.0.tgz#${dist("left-pad", "1.3.0").shasum}"`,
    );
    expect(readLock()).not.toContain("npm.dev.wixpress.com");
    expect(result.output).not.toContain("[CHANGED]");
  });

  it("downgrades a locked version the registry no longer serves to the highest version at or below it", async () => {
    publish("left-pad", "1.2.0", "1.3.5", "1.5.0");
    writeProject({ dependencies: { "left-pad": "^1.3.0" } }, [lockBlock(["left-pad@^1.3.0"], "left-pad", "1.4.0")]);

    const result = await run([]);

    expect(result.code).toBe(0);
    expect(result.output).toContain("[CHANGED] left-pad: 1.4.0 -> 1.3.5");
    expect(readLock()).toContain(`  version "1.3.5"`);
    expect(readLock()).toContain(`  integrity ${dist("left-pad", "1.3.5").integrity}`);
  });

  it("keeps a version the local yarn cache holds from the private host when the registry does not serve it", async () => {
    publish("left-pad", "1.2.0");
    const cached = join(root, "yarn-cache", "npm-left-pad-1.4.0-abc", "node_modules", "left-pad");
    mkdirSync(cached, { recursive: true });
    writeFileSync(
      join(cached, ".yarn-metadata.json"),
      JSON.stringify({
        manifest: { name: "left-pad", version: "1.4.0" },
        remote: { resolved: `${registryUrl}/left-pad/-/left-pad-1.4.0.tgz`, integrity: integrityOf("left-pad", "1.4.0") },
      }),
    );
    writeProject({ dependencies: { "left-pad": "^1.4.0" } }, [lockBlock(["left-pad@^1.4.0"], "left-pad", "1.4.0")]);

    const result = await run([]);

    expect(result.code).toBe(0);
    expect(readLock()).toContain(`  version "1.4.0"`);
    expect(result.output).not.toContain("[CHANGED]");
  });

  it("keeps a version the local npm cache holds from the private host when the registry does not serve it", async () => {
    publish("left-pad", "1.2.0");
    const indexDir = join(root, "npm-cache", "_cacache", "index-v5", "ab", "cd");
    mkdirSync(indexDir, { recursive: true });
    const record = {
      key: `make-fetch-happen:request-cache:${registryUrl}/left-pad/-/left-pad-1.4.0.tgz`,
      integrity: integrityOf("left-pad", "1.4.0"),
    };
    writeFileSync(join(indexDir, "entry"), `deadbeef\t${JSON.stringify(record)}\n`);
    writeProject({ dependencies: { "left-pad": "^1.4.0" } }, [lockBlock(["left-pad@^1.4.0"], "left-pad", "1.4.0")]);

    const result = await run([]);

    expect(result.code).toBe(0);
    expect(readLock()).toContain(`  version "1.4.0"`);
  });

  it("keeps a version the local bun cache holds from the private host when the registry does not serve it", async () => {
    publish("left-pad", "1.2.0");
    mkdirSync(join(root, "bun-cache", `left-pad@1.4.0@@${new URL(registryUrl).host}@@@1`));
    writeProject({ dependencies: { "left-pad": "^1.4.0" } }, [lockBlock(["left-pad@^1.4.0"], "left-pad", "1.4.0")]);

    const result = await run([]);

    expect(result.code).toBe(0);
    expect(readLock()).toContain(`  version "1.4.0"`);
  });

  it("writes scoped packages to the public scoped tarball path", async () => {
    publish("@acme/tool", "2.0.0");
    writeProject({ dependencies: { "@acme/tool": "^2.0.0" } }, [lockBlock(["@acme/tool@^2.0.0"], "@acme/tool", "2.0.0")]);

    const result = await run([]);

    expect(result.code).toBe(0);
    expect(readLock()).toContain(
      `  resolved "${PUBLIC}/@acme/tool/-/tool-2.0.0.tgz#${dist("@acme/tool", "2.0.0").shasum}"`,
    );
  });

  it("pins a package.json range that no longer covers the changed version", async () => {
    publish("left-pad", "1.2.0", "1.3.5");
    writeProject({ dependencies: { "left-pad": "^1.4.0" } }, [lockBlock(["left-pad@^1.4.0"], "left-pad", "1.4.0")]);

    const result = await run([]);

    expect(result.code).toBe(0);
    expect(readPackageJson().dependencies?.["left-pad"]).toBe("1.3.5");
    expect(readLock()).toContain("\nleft-pad@1.3.5:\n");
    expect(readLock()).not.toContain("left-pad@^1.4.0");
  });

  it("leaves the lock untouched when the registry cannot be reached", async () => {
    writeProject({ dependencies: { "left-pad": "^1.3.0" } }, [lockBlock(["left-pad@^1.3.0"], "left-pad", "1.3.0")]);
    const before = readLock();

    const result = await run([], "http://127.0.0.1:9");

    expect(result.code).toBe(1);
    expect(readLock()).toBe(before);
  });

  it("passes --check on a public lock whose versions the registry serves", async () => {
    publish("left-pad", "1.3.0");
    writeProject({ dependencies: { "left-pad": "^1.3.0" } }, [lockBlock(["left-pad@^1.3.0"], "left-pad", "1.3.0")]);
    expect((await run([])).code).toBe(0);

    const result = await run(["--check"]);

    expect(result.code).toBe(0);
  });

  it("fails --check when a resolved URL still points at the private host", async () => {
    publish("left-pad", "1.3.0");
    writeProject({ dependencies: { "left-pad": "^1.3.0" } }, [lockBlock(["left-pad@^1.3.0"], "left-pad", "1.3.0")]);

    const result = await run(["--check"]);

    expect(result.code).toBe(1);
    expect(result.output).toContain("npm.dev.wixpress.com");
  });

  it("fails --check when package.json declares a range the lock does not have", async () => {
    publish("left-pad", "1.3.0");
    writeProject({ dependencies: { "left-pad": "^1.3.0" } }, [lockBlock(["left-pad@^1.3.0"], "left-pad", "1.3.0")]);
    expect((await run([])).code).toBe(0);
    writeProject({ dependencies: { "left-pad": "^1.4.0" } }, [lockBlock(["left-pad@^1.3.0"], "left-pad", "1.3.0")]);

    const result = await run(["--check"]);

    expect(result.code).toBe(1);
    expect(result.output).toContain("[STALE] left-pad@^1.4.0");
  });

  it("fails --check when a locked version is not served by the private registry", async () => {
    publish("left-pad", "1.2.0");
    writeProject({ dependencies: { "left-pad": "^1.4.0" } }, [
      lockBlock(["left-pad@^1.4.0"], "left-pad", "1.4.0", PUBLIC),
    ]);

    const result = await run(["--check"]);

    expect(result.code).toBe(1);
    expect(result.output).toContain("left-pad@1.4.0");
  });
});
