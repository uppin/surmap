#!/usr/bin/env python3
"""Regenerate `src/surmap/demo/kitti_raw.py` from KITTI's public bucket listing.

Enumerates every synced+rectified raw drive in the public `avg-kitti` S3
bucket (the same host SurMap already fetches drive 0009 from), records each
drive's `_sync.zip` size, and pins the five small per-date calibration zips
by SHA-256 (they are ~4 KB, so they are downloaded and hashed here). Drive
zips are *not* downloaded: their SHA-256 is learned on first fetch (see
`surmap.demo.datasets.ensure_dataset`).

    uv run python scripts/list_kitti_raw.py
"""

from __future__ import annotations

import hashlib
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

BUCKET = "https://s3.eu-central-1.amazonaws.com/avg-kitti"
OUT = Path(__file__).resolve().parent.parent / "src/surmap/demo/kitti_raw.py"
_NS = {"s": "http://s3.amazonaws.com/doc/2006-03-01/"}


def _list(prefix: str, *, delimiter: str = "") -> ET.Element:
    url = f"{BUCKET}/?list-type=2&prefix={prefix}"
    if delimiter:
        url += f"&delimiter={delimiter}"
    with urllib.request.urlopen(url, timeout=120) as response:
        return ET.fromstring(response.read())


def _drives() -> list[tuple[str, int]]:
    root = _list("raw_data/", delimiter="/")
    drives: list[tuple[str, int]] = []
    for prefix in root.findall("s:CommonPrefixes", _NS):
        name = (prefix.findtext("s:Prefix", namespaces=_NS) or "").removesuffix("/").split("/")[-1]
        listing = _list(f"raw_data/{name}/")
        for item in listing.findall("s:Contents", _NS):
            key = item.findtext("s:Key", namespaces=_NS) or ""
            if key.endswith("_sync.zip"):
                drives.append((name, int(item.findtext("s:Size", namespaces=_NS) or 0)))
    return sorted(drives)


def _calibrations() -> dict[str, tuple[str, int, str]]:
    root = _list("raw_data/", delimiter="/")
    out: dict[str, tuple[str, int, str]] = {}
    for item in root.findall("s:Contents", _NS):
        key = item.findtext("s:Key", namespaces=_NS) or ""
        if not key.endswith("_calib.zip"):
            continue
        size = int(item.findtext("s:Size", namespaces=_NS) or 0)
        with urllib.request.urlopen(f"{BUCKET}/{key}", timeout=120) as response:
            sha = hashlib.sha256(response.read()).hexdigest()
        out[key.removeprefix("raw_data/").removesuffix("_calib.zip")] = (
            f"{BUCKET}/{key}",
            size,
            sha,
        )
    return out


def main() -> int:
    drives = _drives()
    calibrations = _calibrations()
    lines = [
        '"""Every public KITTI raw drive, generated by `scripts/list_kitti_raw.py` — do not edit.',
        "",
        "Regenerate with `uv run python scripts/list_kitti_raw.py`. Pure data:",
        "each drive's `_sync.zip` size and its date's calibration zip (URL, size,",
        "SHA-256). `surmap.demo.datasets` builds the grey/colour specs from this.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "# date -> (calibration zip URL, size bytes, SHA-256)",
        "KITTI_CALIB: dict[str, tuple[str, int, str]] = {",
    ]
    for date, (url, size, sha) in sorted(calibrations.items()):
        lines.append(f'    "{date}": ("{url}", {size}, "{sha}"),')
    lines += [
        "}",
        "",
        "# (drive, _sync.zip size bytes), sorted by drive",
        "KITTI_DRIVES: tuple[tuple[str, int], ...] = (",
    ]
    for drive, size in drives:
        lines.append(f'    ("{drive}", {size}),')
    lines += [")", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} with {len(drives)} drives ({len(drives) * 2} specs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
